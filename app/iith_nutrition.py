def get_menu_for_day(day: str, meal_type: str):
    day = day.lower()
    meal_type = meal_type.lower()
    items = []
    if meal_type in IITH_MENU:
        if day in IITH_MENU[meal_type]:
            items.extend(IITH_MENU[meal_type][day])
        if "daily" in IITH_MENU[meal_type]:
            items.extend(IITH_MENU[meal_type]["daily"])
    if meal_type == "breakfast":
        items.extend(IITH_MENU["daily"])
    return items


